const { resolve } = require('node:path');
require('dotenv').config({ path: resolve(__dirname, '../.env'), quiet: true });
const express = require('express');
const { createContactApi } = require('./contact-api.cjs');
const app = express();
const api = createContactApi();
const mail = api.locals.mailConfiguration();
if (!mail.configured) console.error(`[mail] Configuração FormSubmit inválida: ${mail.missing.join(', ')}`);
app.use('/api', api);
const port = Number(process.env.API_PORT || 3001);
app.listen(port, '127.0.0.1', () => console.log(`API de contatos: http://127.0.0.1:${port}/api/contacts`));
